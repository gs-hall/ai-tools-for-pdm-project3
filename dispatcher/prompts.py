def case_prompt(case: dict, dialog: list[dict]) -> str:
    lines = [
        f"Дело: {case['case_id']}",
        f"Номер заказа: {case['order_number']}",
        f"Отправитель: {case['sender_name']}",
        f"Тема: {case['subject']}",
        f"Получено: {case['opened_at']}",
        "",
        "Ход диалога:",
    ]
    for message in dialog:
        author = "Клиент" if message["author"] == "customer" else "Служба поддержки"
        lines.append(f"[{author}, {message['created_at']}]\n{message['body']}")
    return "\n".join(lines)
